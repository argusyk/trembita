import numpy as np

# імовірності, які модель приписала справжнім наступним токенам
p_true = np.array([0.62, 0.35, 0.08])  # «прибув», «до», «Ужгорода»
loss = -np.log(p_true).mean()          # середня перехресна ентропія, формула (4.2)
ppl = np.exp(loss)                     # перплексія, формула (4.3)
print(f"втрата = {loss:.3f} нат, перплексія = {ppl:.2f}")
# втрата = 1.351 нат, перплексія = 3.86
